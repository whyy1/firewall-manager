  await page.screenshot({animations: 'disabled', path: 'test-results/screenshots/800-dark-rule-identity-readonly-top.png'})
  await drawer.locator('.n-drawer-body-content-wrapper').evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(drawer.getByText('仅 TCP、UDP 支持端口限制；切换到其他协议会清空端口。', {exact: true})).toBeInViewport()
  await mkdir('test-results/screenshots', {recursive: true})
  await page.screenshot({animations: 'disabled', path: 'test-results/screenshots/800-dark-rule-identity-readonly.png'})
