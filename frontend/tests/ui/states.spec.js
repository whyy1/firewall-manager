test('pending rule and port writes block duplicate submission and closing', async ({page}) => {
  await mockApp(page)
  await expect(page.getByText('共 12 条', {exact: true})).toBeVisible()
  await page.evaluate(() => { window.__mock.holds.UpdateRule = true })
  await page.getByRole('button', {name: '编辑', exact: true}).first().click()
  const drawer = page.locator('.n-drawer')
  await drawer.getByRole('button', {name: '保存', exact: true}).click()
  await expect(drawer.getByRole('button', {name: '保存', exact: true})).toBeDisabled()
  await expect(drawer.getByRole('button', {name: '取消', exact: true})).toBeDisabled()
  await page.evaluate(() => { window.__mock.pending.UpdateRule() })
  await expect(drawer).toBeHidden()
  expect((await calls(page, 'UpdateRule')).length).toBe(1)
  await nav(page, '常用端口').click()
  await page.evaluate(() => { window.__mock.holds.ChangeServicePort = true })
  await page.getByRole('button', {name: '修改RDP 远程桌面端口'}).click()
  const dialog = page.locator('.n-dialog')
  await dialog.locator('input').fill('3390')
  await dialog.getByRole('button', {name: '确认修改'}).click()
  await expect(dialog.locator('input')).toBeDisabled()
  await expect(dialog.getByRole('button', {name: '取消', exact: true})).toBeDisabled()
  await page.evaluate(() => { window.__mock.pending.ChangeServicePort() })
  await expect(dialog).toBeHidden()
  expect((await calls(page, 'ChangeServicePort')).length).toBe(1)
})
