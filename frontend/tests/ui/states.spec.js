test('stopped SMB keeps startup available when protocol and share reads are unavailable', async ({page}) => {
  await mockApp(page)
  await nav(page, 'SMB 文件共享').click()
  await page.getByRole('button', {name: '停止服务', exact: true}).click()
  await page.evaluate(() => {
    window.__mock.values.GetSMBOverview = {...window.__mock.values.GetSMBOverview, serviceRunning: false, serviceStatus: 'Stopped', configurationError: 'SMB 服务未运行，协议安全配置暂不可读取；启动服务后请刷新。'}
    window.__mock.failures.GetSMBShares = '服务已停止，共享查询不可用'
  })
  await page.getByRole('button', {name: '确认停止', exact: true}).click()
  await expect(page.getByRole('button', {name: '启动服务', exact: true})).toBeEnabled()
  await expect(page.getByText('未检测', {exact: true})).toHaveCount(2)
  await expect(page.getByRole('button', {name: '关闭 SMB1', exact: true})).toHaveCount(0)
  await expect(page.getByText(/协议安全配置暂不可读取/)).toBeVisible()
  await page.getByRole('button', {name: '启动服务', exact: true}).click()
  await page.evaluate(() => {
    window.__mock.values.GetSMBOverview = {...window.__mock.values.GetSMBOverview, serviceRunning: true, serviceStatus: 'Running', configurationError: ''}
    window.__mock.failures.GetSMBShares = ''
  })
  await page.getByRole('button', {name: '确认启动', exact: true}).click()
  await expect(page.getByRole('button', {name: '停止服务', exact: true})).toBeEnabled()
  expect((await calls(page, 'SetSMBServiceRunning')).map(call => call.args[0])).toEqual([false, true])
})

