test('SMB directory open requests report success or failure and release busy state', async ({page}) => {
  await mockApp(page)
  await page.getByRole('button', {name: 'SMB 文件共享', exact: true}).click()
  const open = page.getByRole('button', {name: '打开目录', exact: true}).first()
  await open.click()
  await expect(page.getByText('已请求资源管理器打开：C:\\Windows', {exact: true})).toBeVisible()
  await page.evaluate(() => { window.__mock.failures.OpenSMBLocation = '资源管理器启动被拒绝' })
  await open.click()
  await expect(page.getByText(/打开失败:.*资源管理器启动被拒绝/)).toBeVisible()
  await expect(open).toBeEnabled()
  expect((await calls(page, 'OpenSMBLocation')).length).toBe(2)
})